#!/usr/bin/env python3
"""Emit our method on VLG-CBM's CIFAR-100 backbone (CLIP RN50, penultimate layer), Dirichlet 0.5,
seeds 42 / 31 / 7, on the sanity_1111 sandbox code (2026-11-12).

Why: Table 2 compares CIFAR-100 with VLG-CBM's published 65.7, which reads CLIP RN50, while our
CIFAR-100 reads ImageNet ResNet-50 layer4. Paired with gen_vlgcbm_rn50.py (VLG-CBM on our backbone),
this gives the comparison on both backbones.

Same job as gen_vit_b16.py, whose template this reuses: code from the PVC copy of sandbox-fed-cbm at
371153a (checked against the commit), outputs only under /sc-rwx-vol/fedmedcbm/models/CLIP_RN50/.
Differences from the ViT-B/16 job, each asserted below:
  - backbone flags are CIFAR-10's tab:main ones (--backbone clip_RN50 --use_clip_penultimate
    --clip_name RN50), VLG-CBM's CIFAR choice; everything else is CIFAR-100's tab:main setting;
  - fed_dense's CIFAR-100 config gets the same three backbone lines as its CIFAR-10 config;
  - the Table 3 step adds `central`, the head rule on one client holding every row, so the gap to
    VLG-CBM can be split into pipeline and federation (as Table 3's one-client row does);
  - lambda bracket 0.3-3.3x (gen_c100_clip.py's, which landed the IID NEC~5 head at 5.6).
Earlier CLIP RN50 runs of CIFAR-100 (C100_CLIP, IID, older code): head rule 59.6 @ 5.6 at NEC~5.

Stages per seed (each skipped if its output is already on the PVC): main_fed.py Phases 1-3, the head
rule at NEC~5 / ~20, dense FedAvg / FedProx + FedAvg l1 threshold + one client, FedAvg without a
concept layer. Seeds run in sequence (they share the test-set feature cache file).

Sizing: 8 CPU, 10Gi, 3Gi /dev/shm. The ViT-B/16 CIFAR-100 job of the same template used 6.8 of 8 cores
and 6.4 of 8 GiB in main_fed's extraction (Prometheus, 2026-11-13), and vit-b16-cub was OOMKilled at 6Gi
there, so 10Gi leaves headroom while 6.4 GiB stays at 64% of the request (NRP floor 20%). main_fed's
extraction needs ~2.4 GB of shm, which counts against the memory limit.

usage: python3 naut/gen_c100_clip_rn50.py > naut/generated_jobs/c100-clip-rn50.yaml
"""

import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)
import gen_vit_b16 as V  # noqa: E402
from gen_seed_main import CFG, LAMS, CLASSES  # noqa: E402
from gen_jobs import CIFAR_CACHE, LFC_COMMIT, MODELS, dir_lams  # noqa: E402

DS = "cifar100"
OUT_ROOT = f"{MODELS}/CLIP_RN50"
BB = CFG["cifar10"]["bb"]
assert BB == "--backbone clip_RN50 --use_clip_penultimate --clip_name RN50", BB
LAM_MULTS = "0.3 0.55 1.0 1.8 3.3"
CENTRAL_LAMS = "5:0.01 20:0.00228"  # gen_jobs t3-central, CIFAR-100
NECS = (5, 20)
CPU, MEM, DSHM = "8", "10Gi", "3Gi"


def swap(s, old, new, count=1):
    n = s.count(old)
    assert n == count, f"expected {count} x {old!r}, found {n}"
    return s.replace(old, new)


JOB = V.JOB
JOB = swap(JOB, "name: vit-b16-{ds}", "name: clip-rn50-{ds}")
JOB = swap(JOB, "task: vit-b16", "task: clip-rn50")
JOB = swap(JOB, "sed -e 's|^backbone: .*|backbone: clip_ViT-B/16|' baselines/fed_dense/configs/$DS.yaml > $WORKSPACE/fed_dense_vit.yaml",
           "sed -e 's|^backbone: .*|backbone: clip_RN50|' -e 's|^feature_layer: .*|use_clip_penultimate: true|' "
           "-e 's|^clip_name: .*|clip_name: RN50|' baselines/fed_dense/configs/$DS.yaml > $WORKSPACE/fed_dense_clip.yaml")
JOB = swap(JOB, "grep -q '^backbone: clip_ViT-B/16$' $WORKSPACE/fed_dense_vit.yaml",
           "grep -q '^backbone: clip_RN50$' $WORKSPACE/fed_dense_clip.yaml\n"
           "              grep -q '^use_clip_penultimate: true$' $WORKSPACE/fed_dense_clip.yaml\n"
           "              grep -q '^clip_name: RN50$' $WORKSPACE/fed_dense_clip.yaml\n"
           "              if grep -q '^feature_layer:' $WORKSPACE/fed_dense_clip.yaml; then echo 'ERROR: feature_layer left in fed_dense config'; exit 1; fi")
JOB = swap(JOB, "--config $WORKSPACE/fed_dense_vit.yaml", "--config $WORKSPACE/fed_dense_clip.yaml")
JOB = swap(JOB, "###### ViT-B/16 |", "###### CLIP-RN50 |", count=4)
JOB = swap(JOB, "RESULT vit-b16", "RESULT clip-rn50", count=2)
JOB = swap(JOB, "Table 3: dense FedAvg / FedProx, FedAvg + l1 threshold ######",
           "Table 3: dense FedAvg / FedProx, FedAvg + l1 threshold, one client ######")
JOB = swap(JOB, "--parts dense thresh --necs {necs}",
           "--parts dense thresh central --necs {necs} \\\n"
           "                    --central_lams {central_lams} --central_mults {lam_mults}")
assert "vit" not in JOB.lower().replace("{", "").replace("}", ""), "ViT text left in the template"

HEADER = """# Ours on CLIP RN50 (VLG-CBM's CIFAR-100 backbone): CIFAR-100, Dirichlet 0.5, seeds {seeds}.
# GENERATED BY naut/gen_c100_clip_rn50.py -- edit that, not this file.
#
# Code: sandbox-fed-cbm @ {commit}, copied from {code}.
# One CPU-only Job; seeds run in sequence. RESUMABLE: each stage is skipped if its output exists.
# Output: {out_root}/cifar100/dir_s<seed>/<run>/          main_fed.py run (plain FedDualAvg, NEC~50 lambda)
#         {out_root}/cifar100/dir_s<seed>_head/<run>/     head rule, NEC~5 and ~20 (own_100 entries)
#         {out_root}/cifar100/dir_s<seed>_t3/<run>/       dense FedAvg / FedProx, FedAvg + l1 threshold, one client
#         {out_root}/cifar100/dir_s<seed>_fed_dense/<run>/ FedAvg without a concept layer
"""


def main():
    cfg = CFG[DS]
    lams = dir_lams(DS)
    seeds = " ".join(map(str, V.SEEDS))
    val_split = re.search(r"--val_split (\S+)", cfg["args"]).group(1)
    workers = re.search(r"--num_workers (\S+)", cfg["args"]).group(1)
    head_args = (f"--val_split {val_split} --num_workers {workers} --num_clients 5 --alpha 0.5 {V.ANN} "
                 f"--device cpu --extract_batch_size 64")
    job = JOB.format(
        ds=DS, code=V.CODE, commit=V.SANDBOX_COMMIT, lfc=LFC_COMMIT, out_root=OUT_ROOT, seeds=seeds,
        data=f"mkdir -p /root/.cache && cp -rn {CIFAR_CACHE}/. /root/.cache/ 2>/dev/null || true",
        check=cfg["check"],
        cifar_out=f"cp -rn /root/.cache/cifar-* {CIFAR_CACHE}/ 2>/dev/null || true",
        concepts=cfg["concepts"], bb=BB, lam50=LAMS[DS]["dirichlet"][50], args=cfg["args"], common=V.MAIN_COMMON,
        classes=CLASSES[DS], head_args=head_args, lam_mults=LAM_MULTS,
        lam_targets=" ".join(f"dirichlet.{k}:{lams[k]:g}" for k in NECS),
        necs=" ".join(map(str, NECS)), central_lams=CENTRAL_LAMS, cpu=CPU, mem=MEM, dshm=DSHM,
        bad_nodes="\n".join(f"                      - {n}" for n in V.BAD_NODES),
        bad_zones="\n".join(f"                      - {z}" for z in V.BAD_ZONES),
    )
    allowed = {"main_fed.py": V.flags_of("main_fed.py"),
               "heads/ours_head.py": V.flags_of("heads/run.py", "heads/ours_head.py"),
               "heads/dense_prune.py": V.flags_of("heads/run.py", "heads/dense_prune.py"),
               "baselines/fed_dense/run.py": V.flags_of("baselines/fed_dense/run.py")}
    blocks = re.findall(r"python (\S+\.py) (.*?)(?:\n\s*RC=)", job, flags=re.S)
    assert len(blocks) == 4, f"expected 4 python stages, found {len(blocks)}"
    for script, rest in blocks:
        V.check_flags(rest, allowed[script], f"{DS} {script}")
    assert job.count("--use_clip_penultimate") == 3 and "no_nec_eval" not in job
    assert f"{MODELS}/CLIP_RN50/" in job and "VIT_B16" not in job
    sys.stdout.write(HEADER.format(seeds=seeds, commit=V.SANDBOX_COMMIT, code=V.CODE, out_root=OUT_ROOT) + job)


if __name__ == "__main__":
    main()
