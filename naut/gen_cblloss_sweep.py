#!/usr/bin/env python3
"""CBL loss ablation: BCE vs FedCBM's hinge loss for the concept layer. One CPU Job per
(dataset, loss).

Reviewer ask (Overleaf T033, 2026-10-20): why BCE rather than the hinge loss FedCBM uses?
FedCBM's hinge only works on our labels (~1-6% positive per concept) once each concept's
positives and negatives get equal total weight, so hinge here is class-balanced, and the
arms separate the loss from the weighting:
  bcebal   BCE, class-balanced (--cbl_auto_weight --cbl_pos_weight 1.0: positives weighted
           by n_neg / n_pos), the control for the hinge arms
  hinge    class-balanced hinge (utils/loss_vlg.py BalancedHingeLoss), as FedCBM
  sqhinge  class-balanced squared hinge: smooth, as Phase 1's drop-in-optimizer claim assumes
The tab:main loss (BCE, --cbl_pos_weight 0.2) is ORTHO_SWEEP/<ds>/o100, same protocol and
seed, so it is not rerun.

Everything else is tab:main, lambda_ortho 100 included (the ortho sweep found 100-1000 a
plateau, so the loss scale shifting the penalty's relative weight should not matter much).
Each Job is gen_ortho_sweep.py's job at lambda_ortho 100 with the loss flags and the output
path changed: main_fed.py -> CBL weight geometry -> evaluate_cbl.py -> ours_head.py at
NEC~5 / ~50. evaluate_cbl's ECE and F1 at 0.5 assume the score is a log-odds, so for the
hinge arms read AUC and best-threshold F1 only.

Output: /sc-rwx-vol/fedmedcbm/models/CBLLOSS_SWEEP/<dataset>/<arm>/ (layout as ORTHO_SWEEP)

Usage:
    python naut/gen_cblloss_sweep.py > naut/generated_jobs/fedcbm-cblloss.yaml
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_ortho_sweep as gos  # noqa: E402

DATASETS = ("cifar10", "cifar100", "cub")
ARMS = {"bcebal": "--cbl_loss_type bce --cbl_auto_weight",
        "hinge": "--cbl_loss_type hinge",
        "sqhinge": "--cbl_loss_type sqhinge"}

HEADER = """# CBL loss ablation: {datasets} x {{{arms}}}, lambda_ortho 100.
#
# GENERATED BY naut/gen_cblloss_sweep.py -- edit that, not this file.
#
# One CPU-only Job per (dataset, loss); Dirichlet alpha=0.5, tab:main base seed. The BCE
# baseline is ORTHO_SWEEP/<ds>/o100. Needs utils/loss_vlg.py's hinge losses on origin/main.
# RESUMABLE: each step skips itself if its output exists.
# Output: /sc-rwx-vol/fedmedcbm/models/CBLLOSS_SWEEP/<dataset>/<arm>/
"""


def job_for(ds, arm):
    """gen_ortho_sweep's lambda_ortho=100 job, with the loss flags and paths swapped."""
    job = gos.JOB  # format exactly as gen_ortho_sweep.main does, then substitute
    cfg = gos.CFG[ds]
    cpu, mem, dshm = gos.SIZE[ds]
    lam50 = gos.LAMS[ds]["dirichlet"][50]
    cifar_in = (f"mkdir -p /root/.cache {gos.gen_jobs.CIFAR_CACHE} && "
                f"cp -rn {gos.gen_jobs.CIFAR_CACHE}/. /root/.cache/ 2>/dev/null || true"
                if ds.startswith("cifar") else ": # not CIFAR")
    job = job.format(
        ds=ds, o="100", seed=gos.BASE_SEED[ds], models=gos.MODELS, lfc=gos.gen_jobs.LFC_COMMIT,
        kind="cpu", device="cpu", concepts=cfg["concepts"], bb=cfg["bb"], args=cfg["args"],
        common=gos.COMMON_CPU, data=cfg["data"] or ": # no dataset setup needed", check=cfg["check"],
        cifar_in=cifar_in, lam50=lam50, geom=gos.GEOM, lam_targets=gos.gen_jobs.lam_targets(ds),
        eval_step=gos.EVAL_CPU, fda=gos.FDA_CPU,
        val_split=gos.pick("val_split", cfg["args"]), workers=gos.pick("num_workers", cfg["args"]),
        ref=f"{gos.MODELS}/{ds}/dlamsweep/lam{lam50}", classes=gos.CLASSES[ds],
        cpu=cpu, mem=mem, dshm=dshm, gpu="", affinity="")

    def sub(old, new, count=1):
        nonlocal job
        assert job.count(old) == count, f"{ds}/{arm}: expected {count}x {old!r}, found {job.count(old)}"
        job = job.replace(old, new)

    sub(f"  name: fedcbm-ortho-{ds}-o100\n", f"  name: fedcbm-cblloss-{ds}-{arm}\n")
    sub("    task: ortho-sweep\n", "    task: cblloss-sweep\n")
    sub("              O=100\n", f"              O=100\n              ARM={arm}\n")
    sub("/ORTHO_SWEEP/$DS/o$O\n", "/CBLLOSS_SWEEP/$DS/$ARM\n")
    sub("############ $DS | ortho_lambda $O |", "############ $DS | CBL loss $ARM | ortho_lambda $O |")
    sub("SUMMARY: $DS ortho_lambda $O ===", "SUMMARY: $DS CBL loss $ARM ===")
    sub("(second line: tab:main run, ortho_lambda 100, GPU)", "(second line: tab:main run, BCE pos_weight 0.2, GPU)")
    sub("--cbl_loss_type bce ", ARMS[arm] + " ")
    if arm == "bcebal":
        sub("--cbl_pos_weight 0.2 ", "--cbl_pos_weight 1.0 ")
    return job


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--datasets", nargs="+", default=list(DATASETS), choices=DATASETS)
    ap.add_argument("--arms", nargs="+", default=list(ARMS), choices=list(ARMS))
    a = ap.parse_args()
    out = [HEADER.format(datasets=", ".join(a.datasets), arms=", ".join(a.arms))]
    out += [job_for(ds, arm) for ds in a.datasets for arm in a.arms]
    print("".join(out), end="")


if __name__ == "__main__":
    main()
